const GLYPHS = {};
for (const k of Object.keys(RAW)) {
  GLYPHS[k] = RAW[k].split('/');
}

export function textWidth(text, scale = 1, spacing = 1) {
  const s = String(text);
  if (!s.length) return 0;
  return (s.length * (5 + spacing) - spacing) * scale;
}

export function drawText(ctx, text, x, y, opts = {}) {
  const {
    scale = 1,
    color = '#ffffff',
    align = 'left',
    spacing = 1,
    outline = null,
    outlineWidth = 1,
    shadow = null,
    shadowOffset = 1,
    alpha = 1,
    wrapWidth = 0,
  } = opts;
  let str = String(text).toUpperCase();
  str = str.replace(/—/g, '-').replace(/…/g, '...');

  const lines = wrapWidth ? wrapText(str, wrapWidth, scale, spacing) : str.split('\n');
  const lineH = 8 * scale;
  let totalW = 0;
  for (const ln of lines) totalW = Math.max(totalW, textWidth(ln, scale, spacing));

  let baseX = x;
  if (align === 'center') baseX = x - totalW / 2;
  else if (align === 'right') baseX = x - totalW;

  ctx.save();
  ctx.globalAlpha *= alpha;

  const paint = (ox, oy, col) => {
    let yy = y + oy;
    for (const ln of lines) {
      let xx = baseX + ox;
      for (let i = 0; i < ln.length; i++) {
        const ch = ln[i];
        const g = GLYPHS[ch] || GLYPHS['?'];
        for (let r = 0; r < 7; r++) {
          const row = g[r];
          for (let c = 0; c < 5; c++) {
            if (row[c] === '#') {
              ctx.fillStyle = col;
              ctx.fillRect(Math.round(xx + c * scale), Math.round(yy + r * scale), scale, scale);
            }
          }
        }
        xx += (5 + spacing) * scale;
      }
      yy += lineH;
    }
  };

  if (shadow) paint(shadowOffset * scale, shadowOffset * scale, shadow);
  if (outline) {
    const o = outlineWidth * Math.max(1, Math.round(scale * 0.5));
    paint(-o, 0, outline); paint(o, 0, outline); paint(0, -o, outline); paint(0, o, outline);
    paint(-o, -o, outline); paint(o, -o, outline); paint(-o, o, outline); paint(o, o, outline);
  }
  paint(0, 0, color);
  ctx.restore();
  return totalW;
}

function wrapText(str, wrapWidth, scale, spacing) {
  const out = [];
  for (const para of str.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const w of words) {
      const test = line ? line + ' ' + w : w;
      if (textWidth(test, scale, spacing) > wrapWidth && line) {
        out.push(line);
        line = w;
      } else line = test;
    }
    out.push(line);
  }
  return out;
}
